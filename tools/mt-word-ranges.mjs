// Generate the GBNF character class from the same Unicode properties as the decoder.
import {writeFile} from "node:fs/promises";
import {fileURLToPath} from "node:url";
const word = /[\p{L}\p{N}]/u;
const escape = point => "\\" + (point <= 0xffff ? "u" : "U") + point.toString(16).padStart(point <= 0xffff ? 4 : 8, "0");
const ranges = [];
let start = null;
for (let point = 0; point <= 0x110000; point++) {
  if (point < 0x110000 && word.test(String.fromCodePoint(point))) {
    start ??= point;
  } else if (start !== null) {
    ranges.push(escape(start) + (point - 1 === start ? "" : "-" + escape(point - 1)));
    start = null;
  }
}
const source = `// Generated by tools/mt-word-ranges.mjs using Unicode ${process.versions.unicode}; do not edit manually.\n`
  + `export const MT_WORD_CHAR_RANGES = String.raw\`${ranges.join("")}\`;\n`;
await writeFile(fileURLToPath(new URL("../src/providers/pagelingo-mt/word-ranges.ts", import.meta.url)), source);
console.log(JSON.stringify({unicode: process.versions.unicode, ranges: ranges.length, bytes: Buffer.byteLength(source)}));
